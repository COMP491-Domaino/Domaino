"""Human-readable dataset documentation (deliverable D1.2).

Renders the data card and audit report. Every number comes from `audit` or
`splits`, so the prose never asserts anything the pipeline did not measure.
"""

from __future__ import annotations

import json
from typing import Dict, Iterable, List, Mapping, Optional, Sequence

from .audit import SourceAudit
from .splits import SplitPlan


def _table(headers: Sequence[str], rows: Iterable[Sequence[object]]) -> str:
    lines = ["| " + " | ".join(headers) + " |",
             "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        lines.append("| " + " | ".join("" if c is None else str(c) for c in row) + " |")
    return "\n".join(lines)


def _distribution(mapping: Mapping[str, object]) -> str:
    if not mapping:
        return "_none_"
    return ", ".join(f"`{key}`: {value}" for key, value in mapping.items())


def render_audit(
    audits: Mapping[str, SourceAudit],
    label_space: Mapping[str, object],
    conflicts: Mapping[str, object],
    plan: Optional[SplitPlan],
    cathe2_coverage: Mapping[str, object],
    pfam_scan: Optional[Mapping[str, object]] = None,
) -> str:
    """Render the audit report."""
    out: List[str] = ["# Domaino dataset audit", ""]
    out += [
        "Generated by `python -m domaino.data.build`. Counts are measured, not "
        "estimated.",
        "",
        "## Records per source",
        "",
        _table(
            ["source", "records", "usable", "domains", "multidomain", "discontinuous"],
            [
                [
                    audit.source,
                    audit.records,
                    audit.usable,
                    audit.domains,
                    audit.multidomain_records,
                    audit.discontinuous_records,
                ]
                for audit in audits.values()
            ],
        ),
        "",
    ]

    for audit in audits.values():
        out += [
            f"## Source: {audit.source}",
            "",
            f"- chain length: {_distribution(audit.chain_length)}",
            f"- domain length: {_distribution(audit.domain_length)}",
            f"- domain coverage of chain: {_distribution(audit.coverage)}",
            f"- domains per chain: {_distribution(audit.domains_per_chain)}",
            f"- segments per domain: {_distribution(audit.segments_per_domain)}",
            f"- discontinuous domains: {audit.discontinuous_domains}",
            f"- CATH label depth: {_distribution(audit.label_depth)}",
            f"- distinct sequences: {audit.distinct_sequences} "
            f"(duplicate chains sharing a sequence: {audit.duplicate_sequences})",
            "",
        ]
        if audit.agreement:
            out += [
                "Agreement between the canonical SEQRES chopping and CATH's own "
                "published domain sequences:",
                "",
                _distribution(audit.agreement),
                "",
            ]
        if audit.flags:
            out += ["Flags raised:", "", _distribution(audit.flags), ""]

    out += [
        "## CATH label space",
        "",
        f"- labelled domains: {label_space.get('labelled_domains')}",
        f"- distinct nodes per level: {_distribution(label_space.get('distinct', {}))}",
        f"- homologous superfamilies: {label_space.get('h_superfamilies')}",
        f"- superfamilies with one domain: "
        f"{label_space.get('h_singleton_superfamilies')}",
        f"- superfamilies with fewer than ten domains: "
        f"{label_space.get('h_superfamilies_under_10_domains')}",
        f"- share of domains in the largest 1% of superfamilies: "
        f"{label_space.get('h_share_of_top_1_percent')}",
        f"- domains per superfamily: "
        f"{_distribution(label_space.get('h_domains_per_superfamily', {}))}",
        "",
        "The imbalance above is why the proposal plans class-balanced or focal "
        "loss and a confidence threshold on the H level (risk 3).",
        "",
    ]

    out += ["## Annotation conflicts between sources", ""]
    if conflicts and "note" not in conflicts:
        out += [
            "Sources are joined on sequence MD5, so boundaries are only compared "
            "where the residues are provably identical.",
            "",
        ]
        for source, stats in conflicts.items():
            if not isinstance(stats, dict):
                continue
            out += [
                f"### CATH vs {source}",
                "",
                f"- chains describing the same sequence: "
                f"{stats.get('compared_chains')}",
                f"- identical domain count: {stats.get('domain_count_equal')} "
                f"({stats.get('domain_count_agreement')})",
                f"- domain-count difference ({source} minus CATH): "
                f"{_distribution(stats.get('domain_count_delta', {}))}",
                f"- per-domain best IoU: "
                f"{_distribution(stats.get('per_domain_best_iou', {}))}",
                f"- domains matching at IoU >= 0.8: "
                f"{stats.get('domains_matched_at_iou_0.8')}",
                "",
            ]
    else:
        out += [
            "No sequences shared between sources were found, so no boundary "
            "comparison was possible.",
            "",
        ]

    if pfam_scan:
        out += [
            "## Pfam regions scan",
            "",
            f"- rows scanned: {pfam_scan.get('rows_scanned')} "
            f"(truncated: {pfam_scan.get('truncated')})",
            f"- distinct families: {pfam_scan.get('distinct_families')}",
            f"- distinct sequences: {pfam_scan.get('distinct_sequences')}",
            f"- regions per sequence: {pfam_scan.get('regions_per_sequence')}",
            f"- region length: {_distribution(pfam_scan.get('region_length', {}))}",
            "",
        ]

    out += ["## CATHe2 label-space coverage", ""]
    if cathe2_coverage.get("available"):
        out += [
            f"- CATHe2 test domains: {cathe2_coverage.get('cathe2_test_domains')}",
            f"- their distinct superfamilies: "
            f"{cathe2_coverage.get('cathe2_distinct_superfamilies')}",
            f"- covered by our label space: "
            f"{cathe2_coverage.get('covered_superfamilies')}",
            f"- missing: {cathe2_coverage.get('missing_superfamilies')} superfamilies "
            f"({cathe2_coverage.get('missing_test_domains')} test domains)",
            "",
        ]
    else:
        out += ["CATHe2 superfamily labels were not available.", ""]

    if plan is not None:
        leakage = plan.leakage
        out += [
            "## Partitions and homology-leakage audit",
            "",
            _table(
                ["partition", "chains"],
                [[name, count] for name, count in plan.counts.items()],
            ),
            "",
            f"- homology components: {plan.component_count}",
            f"- largest component: {plan.largest_component} chains",
            f"- S35 clusters seen: {leakage.get('clusters_total')}",
            f"- clusters spanning more than one partition: "
            f"{leakage.get('clusters_spanning_partitions')}",
            f"- clusters leaking training into evaluation: "
            f"{leakage.get('clusters_leaking_train_into_eval')}",
            f"- verdict: {'clean' if leakage.get('clean') else 'LEAKAGE DETECTED'}",
            "",
        ]
        if plan.excluded_by_benchmark:
            out += [
                "Chains excluded from training because they are homologues of a "
                "benchmark test chain:",
                "",
                _distribution(plan.excluded_by_benchmark),
                "",
            ]

        # An exclusion that silently did nothing would make the corresponding
        # benchmark comparison look sounder than it is, so say it outright.
        for partition, benchmark in (
            ("benchmark_chainsaw", "Chainsaw segmentation"),
            ("benchmark_cathe2", "CATHe2 classification"),
        ):
            if not plan.counts.get(partition):
                out += [
                    f"> **The {benchmark} exclusion is INACTIVE.** No test "
                    f"chains were reserved for `{partition}`, so training may "
                    "contain homologues of that benchmark's test set and any "
                    "comparison against it is exposed to homology leakage.",
                    "",
                ]

    return "\n".join(out) + "\n"


EXCLUSION_WORDING = {
    "one_hop": (
        "A chain that shares an S35 cluster with a published benchmark test "
        "chain -- that is, one homologous to it at 35% identity or better -- is "
        "never used for training."
    ),
    "component": (
        "Every chain in a homology component containing a published benchmark "
        "test chain is never used for training, including chains linked to it "
        "only through intermediates."
    ),
}


def render_data_card(
    dataset_version: str,
    audits: Mapping[str, SourceAudit],
    plan: Optional[SplitPlan],
    sources: Sequence[Mapping[str, str]],
    label_space: Mapping[str, object],
    benchmark_exclusion: str = "one_hop",
    notes: Sequence[str] = (),
) -> str:
    """Render the dataset data card."""
    out: List[str] = [
        f"# Domaino dataset {dataset_version} -- data card",
        "",
        "## What this dataset is for",
        "",
        "Training and evaluating a sequence-only model that segments a protein "
        "chain into domains and assigns each domain a CATH classification. One "
        "record is one protein chain as a single source annotates it.",
        "",
        "## Sources",
        "",
        _table(
            ["source", "version", "role"],
            [
                [entry.get("source"), entry.get("version"), entry.get("role")]
                for entry in sources
            ],
        ),
        "",
        "## Contents",
        "",
        _table(
            ["source", "records", "usable for training", "domains"],
            [
                [audit.source, audit.records, audit.usable, audit.domains]
                for audit in audits.values()
            ],
        ),
        "",
        "## Coordinate convention",
        "",
        "Every domain segment is a 1-based inclusive interval into the record's "
        "own `sequence`. For CATH the sequence is the PDB SEQRES record of the "
        "chain and the intervals come from "
        "`cath-domain-boundaries-seqreschopping`; that pairing is canonical "
        "because it is the only one that yields a whole-chain sequence with "
        "coordinates defined on it.",
        "",
        "## How supervision differs by source",
        "",
        "Each record carries a `supervision` block stating which targets it may "
        "contribute to. The decisive field is `complete_partition`: CATH chops "
        "an entire chain, so residues outside every domain are genuine linker, "
        "whereas Pfam annotates only the regions it recognises, so an "
        "unannotated residue there is unknown and must never be used as a "
        "negative example.",
        "",
        _table(
            ["source", "residue labels", "pairwise", "CATH labels", "complete partition"],
            [
                ["cath", "yes", "yes", "yes, where classified", "yes"],
                ["pfam", "positive regions only", "no", "no", "no"],
                ["ted", "yes", "high/medium consensus only", "predicted, weak", "yes"],
            ],
        ),
        "",
        "## Partitions",
        "",
    ]

    if plan is not None:
        out += [
            _table(
                ["partition", "chains"],
                [[name, count] for name, count in plan.counts.items()],
            ),
            "",
            "Chains are grouped into homology components by shared CATH S35 "
            "sequence cluster and whole components are assigned together, so no "
            "close homologue spans a training and an evaluation partition. "
            + EXCLUSION_WORDING.get(benchmark_exclusion, ""),
            "",
        ]

    held_out_without_cluster = (plan.counts.get("excluded_no_cluster", 0) if plan else 0)
    out += [
        "## Known limitations",
        "",
        "- CATH 4.4.0 references PDB entries that have since been obsoleted and "
        "removed from `pdb_seqres`; those chains have no sequence and are "
        "excluded from training.",
        f"- {held_out_without_cluster} chains have domain boundaries but no "
        "classified domain, so they carry no S35 cluster and their homology to "
        "the rest of the dataset cannot be established. They are held out of "
        "every partition rather than risking leakage. Clustering them with "
        "MMseqs2, which the proposal names as the alternative to CATH's own "
        "clusters, would recover them as segmentation-only supervision.",
        "- CATH's own files disagree about domain extent for a substantial "
        "minority of domains. Disagreements of a few residues at domain termini "
        "are kept and recorded; anything larger is excluded.",
        "- Pfam and TED ship no sequences. Only their records whose sequence MD5 "
        "matches a chain we already hold carry a sequence and can train.",
        "- TED boundaries derive from predicted structures and carry low weight.",
        "- PDB and CATH over-represent proteins that are easy to crystallise, so "
        "results should be read per class, length and domain count.",
    ]
    out += ["", *(f"- {note}" for note in notes)] if notes else []
    return "\n".join(out) + "\n"


def write_json(path: str, payload: object) -> None:
    with open(path, "wt", encoding="utf-8") as handle:
        json.dump(payload, handle, indent=2, sort_keys=True, default=str)
        handle.write("\n")
